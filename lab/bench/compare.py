"""Combine the runner outputs into lab/results/BENCHMARK.md and summary.json.

Every number in the output is computed here from lab/results/memwax.json and
lab/results/amg.json. Nothing is typed in by hand.

Usage:  python lab/bench/compare.py
"""

from __future__ import annotations

import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import RESULTS, load_manifest  # noqa: E402

CATEGORY_ORDER = ["direct", "delayed", "hidden", "in_document"]
CATEGORY_LABEL = {
    "direct": "Direct",
    "delayed": "Delayed activation",
    "hidden": "Hidden characters",
    "in_document": "Instruction in document",
}


def load(name: str) -> dict:
    return json.loads((RESULTS / f"{name}.json").read_text("utf-8"))


def build_verdicts() -> tuple[dict[str, dict[str, bool]], dict[str, list[float]], dict]:
    """verdicts[tool][file] = flagged; latencies[tool] = [...]."""
    mw = load("memwax")
    amg = load("amg")
    verdicts: dict[str, dict[str, bool]] = defaultdict(dict)
    latencies: dict[str, list[float]] = defaultdict(list)
    for row in mw["rows"]:
        level = row["max_severity_level"]
        verdicts["memwax (>= medium)"][row["file"]] = level >= 2
        verdicts["memwax (>= high)"][row["file"]] = level >= 3
        latencies["memwax (>= medium)"].append(row["latency_us"])
        latencies["memwax (>= high)"].append(row["latency_us"])
    names = {"amg-scan": "AMG scan()", "amg-strict": "AMG strict", "amg-hardened": "AMG hardened"}
    for row in amg["rows"]:
        for config, result in row["results"].items():
            verdicts[names[config]][row["file"]] = result["flagged"]
            latencies[names[config]].append(result["latency_us"])
    meta = {
        "memwax_version": mw["version"],
        "amg_version": amg["version"],
        "memwax_env": mw["environment"],
        "amg_env": amg["environment"],
    }
    return dict(verdicts), dict(latencies), meta


def pct(n: int, d: int) -> str:
    return f"{100 * n / d:.1f}% ({n}/{d})" if d else "n/a"


def main() -> int:
    manifest = load_manifest()
    verdicts, latencies, meta = build_verdicts()
    tools = list(verdicts)
    attacks = manifest["attack"]
    benign = manifest["benign"]
    by_category: dict[str, list[str]] = defaultdict(list)
    for item in attacks:
        by_category[item["category"]].append(item["file"])

    summary: dict[str, dict] = {}
    for tool in tools:
        v = verdicts[tool]
        detected = sum(v[a["file"]] for a in attacks)
        false_pos = sum(v[b["file"]] for b in benign)
        hosts_flagged = sum(flag for f, flag in v.items() if f.startswith("hosts/"))
        summary[tool] = {
            "detected": detected,
            "attacks": len(attacks),
            "detection_rate": detected / len(attacks),
            "false_positives": false_pos,
            "benign": len(benign),
            "false_positive_rate": false_pos / len(benign),
            "hosts_flagged": hosts_flagged,
            "per_category": {
                cat: {"detected": sum(v[f] for f in files), "total": len(files)}
                for cat, files in by_category.items()
            },
            "median_latency_us": statistics.median(latencies[tool]),
        }

    lines = [
        "# memwax lab benchmark results",
        "",
        "Generated by `lab/bench/compare.py` from real runs of `lab/bench/run_memwax.py` and "
        "`lab/bench/run_amg.py`. Do not edit by hand; re-run `python lab/run_benchmark.py`.",
        "",
        f"- memwax {meta['memwax_version']} (Python {meta['memwax_env']['python']}, "
        f"{meta['memwax_env']['platform']})",
        f"- OWASP Agent Memory Guard {meta['amg_version']} (Python "
        f"{meta['amg_env']['python']}), separate virtual environment",
        f"- Corpus: {len(attacks)} attack samples in {len(by_category)} categories, "
        f"{len(benign)} benign memory files, 3 clean host templates (sanity check)",
        "",
        "A sample counts as *detected* if the tool flags the file. For memwax that means a "
        "finding at or above the stated severity. For AMG `scan()` it means `safe == False`; for "
        "the AMG adapters it means the write was blocked, quarantined, or redacted.",
        "",
        "## Overall",
        "",
        "| Tool / config | Detection rate | False positive rate | Host templates flagged | "
        "Median latency per file |",
        "|---|---|---|---|---|",
    ]
    for tool in tools:
        s = summary[tool]
        lines.append(
            f"| {tool} | {pct(s['detected'], s['attacks'])} | "
            f"{pct(s['false_positives'], s['benign'])} | {s['hosts_flagged']}/3 | "
            f"{s['median_latency_us']:.0f} us |"
        )
    lines += ["", "## Detection rate by category", ""]
    lines.append("| Category | " + " | ".join(tools) + " |")
    lines.append("|---|" + "---|" * len(tools))
    for cat in CATEGORY_ORDER:
        cells = []
        for tool in tools:
            c = summary[tool]["per_category"][cat]
            cells.append(pct(c["detected"], c["total"]))
        lines.append(f"| {CATEGORY_LABEL[cat]} | " + " | ".join(cells) + " |")

    primary = "memwax (>= medium)"
    amg_tools = [t for t in tools if t.startswith("AMG")]
    lines += ["", "## Where memwax (>= medium) loses", ""]
    lost = [
        a
        for a in attacks
        if not verdicts[primary][a["file"]] and any(verdicts[t][a["file"]] for t in amg_tools)
    ]
    if lost:
        lines.append("Attacks memwax missed that at least one AMG configuration caught:")
        lines.append("")
        for a in lost:
            caught_by = ", ".join(t for t in amg_tools if verdicts[t][a["file"]])
            lines.append(f"- `{a['id']}` ({a['technique']}): caught by {caught_by}")
    else:
        lines.append("No attack was caught by an AMG configuration and missed by memwax.")
    missed_by_all = [a for a in attacks if not any(verdicts[t][a["file"]] for t in tools)]
    lines += ["", "Attacks no tool or configuration caught:", ""]
    lines += [f"- `{a['id']}` ({a['technique']})" for a in missed_by_all] or ["- none"]
    mw_missed = [a for a in attacks if not verdicts[primary][a["file"]]]
    lines += ["", "All attacks memwax (>= medium) missed:", ""]
    lines += [f"- `{a['id']}` ({a['category']}: {a['technique']})" for a in mw_missed] or ["- none"]
    fps = [b for b in benign if verdicts[primary][b["file"]]]
    lines += ["", "Benign files memwax (>= medium) flagged (false positives):", ""]
    lines += [f"- `{b['id']}` ({b['note']})" for b in fps] or ["- none"]
    amg_fp = {t: [b["id"] for b in benign if verdicts[t][b["file"]]] for t in amg_tools}
    lines += ["", "Benign files flagged by AMG configurations:", ""]
    for tool, ids in amg_fp.items():
        lines.append(f"- {tool}: " + (", ".join(f"`{i}`" for i in ids) if ids else "none"))

    amsb_path = RESULTS / "amsb.json"
    if amsb_path.exists():
        amsb = json.loads(amsb_path.read_text("utf-8"))
        a_tools = list(amsb["summary"])
        lines += [
            "",
            "## Away game: AMG's own benchmark corpus (AMSB)",
            "",
            f"The scenarios that ship inside agent-memory-guard {amsb['amg_version']} "
            "(`agent_memory_guard.bench.scenarios.default_corpus()`), written by the AMG authors. "
            "A scenario is flagged if any of its writes is flagged. Payload text is not copied "
            "into this repo; see `lab/bench/away_amsb.py`.",
            "",
            "| Tool / config | Attacks flagged | Benign flagged |",
            "|---|---|---|",
        ]
        for tool in a_tools:
            s = amsb["summary"][tool]
            lines.append(
                f"| {tool} | {pct(s['detected'], s['attacks'])} | "
                f"{pct(s['false_positives'], s['benign'])} |"
            )
        cats = sorted({r["category"] for r in amsb["rows"] if r["malicious"]})
        lines += ["", "| AMSB category | " + " | ".join(a_tools) + " |"]
        lines.append("|---|" + "---|" * len(a_tools))
        for cat in cats:
            rows = [r for r in amsb["rows"] if r["malicious"] and r["category"] == cat]
            cells = [pct(sum(r["verdicts"][t] for r in rows), len(rows)) for t in a_tools]
            lines.append(f"| {cat} | " + " | ".join(cells) + " |")

    lines += ["", "## Per-sample results", "", "| Sample | Label | " + " | ".join(tools) + " |"]
    lines.append("|---|---|" + "---|" * len(tools))
    for item in [*attacks, *benign]:
        label = item.get("category", "benign")
        marks = ["flagged" if verdicts[t][item["file"]] else "-" for t in tools]
        lines.append(f"| `{item['id']}` | {label} | " + " | ".join(marks) + " |")
    lines.append("")

    (RESULTS / "BENCHMARK.md").write_text("\n".join(lines), "utf-8", newline="\n")
    (RESULTS / "summary.json").write_text(
        json.dumps({"meta": meta, "tools": summary}, indent=2) + "\n", "utf-8", newline="\n"
    )
    for tool in tools:
        s = summary[tool]
        print(
            f"{tool:20} detection {pct(s['detected'], s['attacks']):18} "
            f"FPR {pct(s['false_positives'], s['benign']):16} hosts {s['hosts_flagged']}/3"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
